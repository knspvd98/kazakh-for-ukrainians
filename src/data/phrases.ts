function inferGrammarLinks(kk: string): string[] {
  const links = new Set<string>();
  if (/\bбар\b|\bжоқ\b/.test(kk)) links.add("g-bar-joq");
  if (/\bкерек\b/.test(kk)) links.add("g-need");
  if (kk.includes("келеді") || kk.includes("келемін") || kk.includes("барғым") || kk.includes("демалғым")) links.add("g-want");
  if (kk.includes(" ба?") || kk.includes(" бе?") || kk.includes(" па?") || kk.includes(" пе?") || kk.includes(" ма?") || kk.includes(" ме?")) links.add("g-question-particles");
  if (kk.includes("қайда") || kk.includes("Қайда") || kk.includes("қашан") || kk.includes("Қашан") || kk.includes("қанша") || kk.includes("Қанша")) links.add("g-question-words");
  return [...links];
}

function splitWords(kk: string): string[] {
  return kk
    .replace(/[?.!,:]/g, "")
    .split(/\s+/)
    .filter(Boolean);
}

